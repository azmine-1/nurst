def font_tile(char, color="3"):
    """Render a font glyph into an 8x8 tile, indented one pixel from the left."""
    rows = FONT[char]
    tile = []
    for row in rows:
        tile.append(" " + "".join(color if pixel == "#" else "." for pixel in row) + "  ")
    tile.append("." * 8)
    return [row.replace(" ", ".") for row in tile]


