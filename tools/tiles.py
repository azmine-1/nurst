def mirror(block):
    """Flip a block horizontally."""
    return [row[::-1] for row in block]


def slice16(block):
    """Split a 16x16 block into the four 8x8 tiles of a metasprite."""
    top_left = [row[:8] for row in block[:8]]
    bottom_left = [row[:8] for row in block[8:]]
    top_right = [row[8:] for row in block[:8]]
    bottom_right = [row[8:] for row in block[8:]]
    return [top_left, bottom_left, top_right, bottom_right]


def encode(tile):
    """Pack an 8x8 tile into the NES's two-bitplane format."""
    plane0, plane1 = [], []
    for row in tile:
        low = high = 0
        for x, pixel in enumerate(row):
            value = 0 if pixel in "." else int(pixel)
            low |= (value & 1) << (7 - x)
            high |= ((value >> 1) & 1) << (7 - x)
        plane0.append(low)
        plane1.append(high)
    return bytes(plane0 + plane1)


BLANK = ["........"] * 8


def build_background_table():
    """Pattern table 0. Text tiles sit at their ASCII codes."""
    tiles = [BLANK] * 256
    named = {
        0x01: SKY, 0x02: STAR, 0x03: CLOUD_LEFT, 0x04: CLOUD_RIGHT,
        0x05: GRASS, 0x06: DIRT, 0x07: DIRT_ROCK,
        0x08: BUSH_LEFT, 0x09: BUSH_RIGHT,
        0x0A: HILL_LEFT, 0x0B: HILL_TOP, 0x0C: HILL_RIGHT,
        0x0D: SOLID, 0x0E: BAR, 0x0F: HILL_BODY,
    }
    for index, tile in named.items():
        tiles[index] = tile
    for char in FONT:
        tiles[ord(char)] = font_tile(char)
    return b"".join(encode(tile) for tile in tiles)


def build_sprite_table():
    """Pattern table 1."""
    tiles = [BLANK] * 256
    tiles[0x01] = SPRITE_ZERO
    for base, block in ((0x10, RUNNER_A), (0x14, RUNNER_B), (0x18, RUNNER_JUMP),
                        (0x20, CACTUS), (0x30, mirror(BIRD_A)), (0x34, mirror(BIRD_B))):
        for offset, tile in enumerate(slice16(block)):
            tiles[base + offset] = tile
    return b"".join(encode(tile) for tile in tiles)


def build_chr():
    return build_background_table() + build_sprite_table()
